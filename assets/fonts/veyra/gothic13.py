def pad(art, top):
    """Moves art from the 10-row Veyra Display box down by `top` rows."""
    rows = vf.rows_of(art.lstrip('\n'))
    w = max(len(r) for r in rows)
    return '\n'.join(['.' * w] * top + rows)


# Figures and punctuation from Veyra Display, figures as small-cap height (old style).
DIGITS = {c: pad('\n'.join(vf.rows_of(a)[i] for i in (0, 1, 2, 3, 4, 6, 7, 8, 9)), CAP - XH)
          for c, a in vf.DIGITS.items()}
PUNCT = {c: pad(a, CAP - 10) for c, a in vf.PUNCT.items()}

glyphs = vf.make(CAPS, SMALL, SMALL_ROWS, DIGITS, PUNCT, CAP, XH, space=5)

if __name__ == '__main__':
    vf.build(sys.argv[1], glyphs, 'Veyra Gothic', CAP, ABOVE, BELOW, XH)
