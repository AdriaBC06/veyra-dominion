class G(g18.G):
    def stem(self, x, y0, y1, w=4):
        return self.rect(x, y0, x + w - 1, y1)

    def horns(self, x, y=0):
        """Horns over a 4 px stem at x."""
        self.p(x - 1, y).p(x + 4, y).rect(x - 1, y + 1, x, y + 1).rect(x + 3, y + 1, x + 4, y + 1)
        return self

    def foot(self, x, y=H - 1, flick=True):
        self.rect(x + 1, y, x + 4, y)
        if flick:
            self.p(x + 5, y - 1)
        return self

    def spade(self, x, y):
        return self.art(x - 3, y - 3, """
...#...
..###..
.#####.
#######
.#####.
..###..
...#...""")


