def make():
    gl = {}

    def add(ch, px, adv=None):
        m = min(x for x, _ in px)
        px = {(x - m, y) for x, y in px}
        w = max((x for x, y in px if y < H), default=0) + 1
        gl[ch] = (px, adv if adv is not None else w + 3)

    for ch, g in letters().items():
        add(ch, g.px)
    drop = H - XH
    for ch, (px, adv) in g18.glyphs.items():
        if ch.isupper():
            # Veyra Gothic's capitals are this face's small caps
            gl[ch.lower()] = ({(x, y + drop) for x, y in px}, adv + 1)
        elif not ch.isalpha():
            gl[ch] = ({(x, y + drop) for x, y in px}, adv + 1 if ch != ' ' else 9)
    marks = {'acute': [(3, 0), (4, 0), (2, 1), (3, 1), (1, 2), (2, 2)],
             'diaer': [(0, 1), (1, 1), (0, 2), (1, 2), (5, 1), (6, 1), (5, 2), (6, 2)],
             'tilde': [(1, 0), (2, 0), (0, 1), (3, 1), (6, 1), (4, 2), (5, 2), (7, 0)]}
    for ch, (base, mark) in vf.COMPOSED.items():
        if base.isupper():
            px, adv = gl[base]
            w = max(x for x, _ in px) + 1
            mk = marks[mark]
            mw = max(x for x, _ in mk) + 1
            gl[ch] = (px | {(x + (w - mw) // 2, y - 5) for x, y in mk}, adv)
    return gl


glyphs = make()

if __name__ == '__main__':
    vf.build(sys.argv[1], glyphs, 'Veyra Gothic Titling', H, ABOVE, BELOW, XH)
