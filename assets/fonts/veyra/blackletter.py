ACCENTS = {
    'acute': ["...##", "..##.", ".##.."],
    'grave': ["##...", ".##..", "..##."],
    'diaer': ["##..##", "##..##"],
    'tilde': [".##...#", "#..##.#", "#...##."],
}
COMPOSED = {
    'Á': ('A', 'acute'), 'É': ('E', 'acute'), 'Í': ('I', 'acute'), 'Ó': ('O', 'acute'),
    'Ú': ('U', 'acute'), 'Ü': ('U', 'diaer'), 'Ñ': ('N', 'tilde'), 'À': ('A', 'grave'),
    'à': ('a', 'grave'), 'á': ('a', 'acute'), 'é': ('e', 'acute'), 'í': ('ı', 'acute'), 'ó': ('o', 'acute'),
    'ú': ('u', 'acute'), 'ü': ('u', 'diaer'), 'ñ': ('n', 'tilde'),
}
SPACE = 6


def pixels(top, art):
    px = set()
    for y, row in enumerate(art.strip('\n').split('\n')):
        for x, c in enumerate(row):
            if c == '#':
                px.add((x, y + top))
    return px


def make():
    g = {}
    for ch, (top, art) in G.items():
        px = pixels(top, art)
        g[ch] = (px, vf.width(px) + 2)
    # dotless i for í
    ipx = {(x, y) for x, y in g['i'][0] if y >= LOW}
    g['ı'] = (ipx, g['i'][1])
    g[' '] = (set(), SPACE)
    for ch, (base, mark) in COMPOSED.items():
        px, adv = g[base]
        w = vf.width(px)
        rows = ACCENTS[mark]
        mw = len(rows[0])
        top = (LOW if base.islower() or base == 'ı' else 0) - len(rows) - 1
        # centre over the main stem body: the mean x of the glyph's pixels
        xs = [x for x, _ in px]
        cx = round(sum(xs) / len(xs))
        ox = max(0, min(w - mw, cx - mw // 2))
        m = {(x + ox, y + top) for x, y in pixels(0, '\n'.join(rows))}
        g[ch] = (px | m, adv)
    del g['ı']
